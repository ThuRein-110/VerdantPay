const screenshots=resolve('test-results/finance-preview');
async function signedIn(context:BrowserContext,actor:Actor='admin') {
 await context.addCookies([{name:'sb-127-auth-token',value:cookie(actor),url:frontend,httpOnly:true,sameSite:'Lax'},
  {name:'memo-locale',value:'en',url:frontend,sameSite:'Lax'}]);
}
const overflow= (page:Page)=>expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
function watchErrors(page:Page) {
 const errors:string[]=[];
 page.on('pageerror',error=>errors.push(error.message));
 page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
 return errors;
}
